"""Emit a Vercel Build Output API (v3) directory for a Chano project.

    .vercel/output/
    ├── config.json              rewrites for dynamic routes and /docs
    ├── static/                  public/, plus openapi.json and docs.html
    └── functions/
        ├── index.func/                   one function per route.py
        ├── api/hello.func/
        └── api/items/[item_id].func/
            ├── .vc-config.json
            ├── vc__handler__python.py    trampoline into vercel-runtime
            ├── index.py                  exposes this route's ASGI ``app``
            ├── app/ ...                  project source
            └── _vendor/                  dependencies for the target platform

With ``base_path = "/api"`` in ``[tool.chano]``, function paths, ``static/``
files and rewrites are all prefixed: ``functions/api.func``,
``static/api/docs.html``, ``^/api/docs$``.

Every function carries the project source and its own tree-shaken subset of
dependencies (hard-linked on disk from a shared store), differing in its
entrypoint, ``.vc-config.json`` and ``_vendor/``. The function layout mirrors
what Vercel's own Python builder produces.
"""

